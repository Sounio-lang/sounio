#!/usr/bin/env python3
"""Prototype FPGA-profile emitter (ADR-022), outside `souc`.

Translates ONE kernel function written in the restricted FPGA subset
of Sounio to HLS C++:

  supported: i64/bool scalars, static i64 arrays ([i64; N], [[i64; K]; N]),
  var/let declarations, bounded `for x in A..B`, if/else, comparisons,
  array indexing, integer arithmetic, a trailing bare expression as
  the return value.
  rejected:  everything else (calls, strings, while, heap, floats).
  Rejection is loud: any unrecognised line aborts the emission.

This is prototype tooling, not a claim oracle (ADR-009): the semantics
of the generated kernel are judged by the Futhark reference
(scripts/research/san_scan_reference.fut) via
scripts/ci/fpga_prototype_gate.sh.
"""

import pathlib
import re
import sys

SCALARS = {"i64": "int64_t", "bool": "bool"}


def fail(msg):
    print(f"SIO_FPGA_EMIT_FAIL: {msg}", file=sys.stderr)
    sys.exit(1)


def split_top(text):
    parts, depth, cur = [], 0, ""
    for ch in text:
        if ch == "[":
            depth += 1
        elif ch == "]":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        parts.append(cur.strip())
    return parts


def c_type(sounio_type):
    """Return (base, suffix) for a Sounio profile type."""
    sounio_type = sounio_type.strip()
    if sounio_type in SCALARS:
        return SCALARS[sounio_type], ""
    m = re.fullmatch(r"\[(.+);\s*(\d+)\]", sounio_type)
    if m:
        base, inner = c_type(m.group(1))
        return base, f"[{m.group(2)}]" + inner
    fail(f"unsupported type: {sounio_type}")


def clean_expr(expr):
    expr = re.sub(r"\s+as\s+usize", "", expr)
    if '"' in expr or "'" in expr:
        fail(f"strings are outside the FPGA profile: {expr}")
    return expr.strip()


def translate(source, kernel_name):
    lines = source.splitlines()
    sig_i = None
    for i, line in enumerate(lines):
        if re.search(rf"^\s*fn\s+{kernel_name}\s*\(", line):
            sig_i = i
            break
    if sig_i is None:
        fail(f"kernel function {kernel_name} not found")

    sig = lines[sig_i]
    m = re.search(rf"fn\s+{kernel_name}\s*\((.*)\)\s*->\s*(\w+)", sig)
    if not m:
        fail(f"cannot parse signature: {sig.strip()}")
    params = []
    for part in split_top(m.group(1)):
        pm = re.fullmatch(r"(\w+):\s*(.+)", part)
        if not pm:
            fail(f"cannot parse parameter: {part}")
        base, suffix = c_type(pm.group(2))
        params.append((pm.group(1), base, suffix))
    ret = SCALARS.get(m.group(2))
    if ret is None:
        fail(f"unsupported return type: {m.group(2)}")

    decl = ", ".join(f"{base} {name}{suffix}" for name, base, suffix in params)
    out = [
        "// GENERATED by tools/fpga/sio_fpga_emit.py (ADR-022 prototype)",
        "// Source kernel: Sounio FPGA profile subset. Do not edit by hand.",
        "#include <cstdint>",
        "",
        f'extern "C" {ret} {kernel_name}({decl}) {{',
    ]
    for name, base, suffix in params:
        if suffix:
            out.append(f"#pragma HLS INTERFACE m_axi port={name}")
        else:
            out.append(f"#pragma HLS INTERFACE s_axilite port={name}")
    out.append("#pragma HLS INTERFACE s_axilite port=return")

    depth = 1
    pipeline_done = False
    for line in lines[sig_i + 1 :]:
        s = line.strip()
        if depth == 0:
            break
        if not s or s.startswith("//"):
            continue
        if re.match(r"^fn\s+", s):
            break
        fm = re.fullmatch(r"for\s+(\w+)\s+in\s+(.+)\.\.(.+)\s*\{", s)
        if fm:
            var, lo, hi = fm.group(1), clean_expr(fm.group(2)), clean_expr(fm.group(3))
            out.append(f"for (int64_t {var} = {lo}; {var} < {hi}; {var}++) {{")
            if not pipeline_done:
                out.append("#pragma HLS PIPELINE II=1")
                pipeline_done = True
            depth += 1
            continue
        if s == "}":
            depth -= 1
            if depth >= 1:
                out.append("}")
            continue
        if re.fullmatch(r"\}\s*else\s*\{", s):
            out.append("} else {")
            continue
        dm = re.fullmatch(r"(?:var|let)\s+(\w+)(?::\s*([\w\[\]; ]+))?\s*=\s*(.+)", s)
        if dm:
            ty = SCALARS.get((dm.group(2) or "i64").strip(), "int64_t")
            out.append(f"{ty} {dm.group(1)} = {clean_expr(dm.group(3))};")
            continue
        im = re.fullmatch(r"if\s+(.+)\s*\{", s)
        if im:
            out.append(f"if ({clean_expr(im.group(1))}) {{")
            depth += 1
            continue
        if re.search(r"\bwhile\b|\bprint\b", s):
            fail(f"construct outside the FPGA profile: {s}")
        call = re.search(r"(\w+)\s*\(", s)
        if call and call.group(1) not in ("if", "for"):
            fail(f"calls are outside the FPGA profile: {s}")
        if re.fullmatch(r"[\w\[\] +\-*/%<>=!&|]+", s) and ("=" not in s or "==" in s or ">=" in s or "<=" in s):
            out.append(f"return {clean_expr(s)};")
            continue
        out.append(f"{clean_expr(s)};")
    out.append("}")
    return "\n".join(out) + "\n"


TB = r"""
#include <cstdint>
#include <cstdio>
extern "C" int64_t san_scan(int64_t confs[256][7], int64_t n_samples,
                            int64_t q_delta, int64_t lut[8], int64_t hist[8]);
int main() {
    static int64_t confs[256][7];
    int64_t lut[8], hist[8] = {0};
    long long n, q;
    if (scanf("%lld %lld", &n, &q) != 2) return 2;
    for (int i = 0; i < 8; i++) scanf("%lld", (long long*)&lut[i]);
    for (long long s = 0; s < n; s++)
        for (int k = 0; k < 7; k++) scanf("%lld", (long long*)&confs[s][k]);
    int64_t macs = san_scan(confs, n, q, lut, hist);
    for (int i = 0; i < 8; i++) printf("%lld ", (long long)hist[i]);
    printf("\n%lld\n", (long long)macs);
    return 0;
}
"""


def main():
    if len(sys.argv) < 3:
        fail("usage: sio_fpga_emit.py <kernel.sio> <out.cpp> [--tb <tb.cpp>]")
    kernel = "san_scan"
    if "--kernel" in sys.argv:
        kernel = sys.argv[sys.argv.index("--kernel") + 1]
    source = pathlib.Path(sys.argv[1]).read_text()
    out = translate(source, kernel)
    pathlib.Path(sys.argv[2]).write_text(out)
    if "--tb" in sys.argv:
        pathlib.Path(sys.argv[sys.argv.index("--tb") + 1]).write_text(TB)
    print(f"SIO_FPGA_EMIT_OK kernel={kernel} out={sys.argv[2]}")


if __name__ == "__main__":
    main()
