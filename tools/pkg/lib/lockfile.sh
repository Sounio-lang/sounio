# Remove a package from the lockfile
# Usage: lockfile_remove "Sounio.lock" "package_name"
lockfile_remove() {
    local file="$1"
    local remove_name="$2"

    [[ ! -f "$file" ]] && return 1

    local temp_file="${file}.tmp"
    local in_package=false
    local skip_package=false
    local current_name=""
    local buffer=""

    while IFS= read -r line || [[ -n "$line" ]]; do
        # Detect start of package
        if [[ "$line" == "[[package]]" ]]; then
            # Write previous package if not skipping
            if [[ -n "$buffer" && "$skip_package" == false ]]; then
                printf '%s\n' "$buffer" >> "$temp_file"
            fi
            in_package=true
            skip_package=false
            current_name=""
            buffer="$line"
            continue
        fi

        if $in_package; then
            buffer="$buffer
$line"

            if [[ "$line" =~ ^name[[:space:]]*=[[:space:]]*\"(.+)\"$ ]]; then
                current_name="${BASH_REMATCH[1]}"
                if [[ "$current_name" == "$remove_name" ]]; then
                    skip_package=true
                fi
            fi
        else
            # Outside of package, write directly
            printf '%s\n' "$line" >> "$temp_file"
        fi
    done < "$file"

    # Write last package
    if [[ -n "$buffer" && "$skip_package" == false ]]; then
        printf '%s\n' "$buffer" >> "$temp_file"
    fi

    mv "$temp_file" "$file"
}

# List all packages in lockfile
# Usage: lockfile_list "Sounio.lock"
lockfile_list() {
    local file="$1"

    [[ ! -f "$file" ]] && return 1

    grep -E '^name\s*=' "$file" | sed 's/^name\s*=\s*"\(.*\)"/\1/'
}

