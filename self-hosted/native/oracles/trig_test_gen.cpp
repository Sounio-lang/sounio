// Writes tests/run-pass/builtin_trig_double_precision.sio: the native sin / cos
// builtins against glibc sinl / cosl (long double, rounded to double).
// Prediction written before the run: absolute error below 1e-15 for |x| <= 10
// and below 1e-14 for |x| <= 200 (Cody-Waite reduction error grows like
// |n| * 2^-77 * 2 pi; the series and Horner rounding stay near 1e-16).
#include <cmath>
#include <cstdio>
#include <vector>
int main(int argc, char** argv) {
  std::vector<double> xs;
  for (int i = -400; i <= 400; ++i) xs.push_back(i * 0.025);         // [-10, 10]
  for (int i = -100; i <= 100; ++i) xs.push_back(i * 1.9937);        // [-200, 200]
  for (double x : {3.0, 3.14159265358979, 3.141592653589793, 1.5707963267948966, 6.283185307179586, 1e-8, -1e-8, 100.0, 117.25})
    xs.push_back(x);
  FILE* f = std::fopen(argc > 1 ? argv[1] : "builtin_trig_double_precision.sio", "w");
  std::fprintf(f, "//@ run-pass\n//@ expect-stdout: BUILTIN_TRIG_DOUBLE_PRECISION_OK\n");
  std::fprintf(f, "// Generated by self-hosted/native/oracles/trig_test_gen.cpp: glibc sinl / cosl in\n");
  std::fprintf(f, "// long double, rounded to double. Before the fix cos(3.0) was -0.98993963\n");
  std::fprintf(f, "// (truth -0.98999250): Taylor through r^12 on [-pi, pi].\n\n");
  std::fprintf(f, "fn absd(v: f64) -> f64 { if v < 0.0 { 0.0 - v } else { v } }\n\n");
  std::fprintf(f, "fn main() -> i32 with IO, Mut, Div, Panic {\n    let n = %zu\n", xs.size());
  auto arr = [&](const char* name, auto fn) {
    std::fprintf(f, "    let %s: [f64; %zu] = [", name, xs.size());
    for (size_t i = 0; i < xs.size(); ++i) std::fprintf(f, "%s%.16e", i ? ", " : "", fn(xs[i]));
    std::fprintf(f, "]\n");
  };
  arr("xs", [](double x) { return x; });
  arr("sn", [](double x) { return (double)sinl((long double)x); });
  arr("cs", [](double x) { return (double)cosl((long double)x); });
  std::fprintf(f, "    var worst_small = 0.0\n    var worst_large = 0.0\n    var bad = 0\n    var i = 0\n    while i < n {\n");
  std::fprintf(f, "        let x = xs[i]\n        var d = absd(sin(x) - sn[i])\n        let dc = absd(cos(x) - cs[i])\n        if dc > d { d = dc }\n");
  std::fprintf(f, "        if absd(x) <= 10.0 {\n            if d > worst_small { worst_small = d }\n            if d > 1.0e-15 { bad = bad + 1 }\n        } else {\n");
  std::fprintf(f, "            if d > worst_large { worst_large = d }\n            if d > 1.0e-14 { bad = bad + 1 }\n        }\n        i = i + 1\n    }\n");
  std::fprintf(f, "    print(\"worst abs err |x|<=10: \"); println(worst_small * 1.0e16)\n");
  std::fprintf(f, "    print(\"worst abs err |x|<=200: \"); println(worst_large * 1.0e16)\n");
  std::fprintf(f, "    if bad != 0 { print_int(bad); println(\" points out of bound\"); return 1 }\n");
  std::fprintf(f, "    println(\"BUILTIN_TRIG_DOUBLE_PRECISION_OK\")\n    0\n}\n");
  std::fclose(f);
}
