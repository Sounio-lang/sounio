// Reference values for special::erf (fdlibm port). glibc erfl/erfcl in long double,
// rounded to double, on a grid that hits every branch boundary of s_erf.c.
// Writes tests/stdlib/special/erf_double_precision.sio (the table and the check).
// Prediction written before the run: the Sounio port is within 2 ulp of the
// correctly rounded value at every point (fdlibm itself claims < 1 ulp; the
// port adds the error of math::pure::exp, about 1 ulp).
#include <cmath>
#include <cstdio>
#include <vector>
int main(int argc, char** argv) {
  const char* out = argc > 1 ? argv[1] : "erf_double_precision.sio";
  std::vector<double> xs;
  for (int i = 0; i <= 340; ++i) xs.push_back(-6.0 + 34.0 * i / 340.0);        // [-6, 28] coarse
  for (double b : {3.725290298461914e-9, 1e-12, 0.25, 0.84375, 1.25, 2.857142857142857, 6.0, 26.5, 27.99})
    for (double s : {-1.0, 1.0}) for (double e : {0.0, 1e-15, -1e-15, 1e-9, -1e-9}) xs.push_back(s * (b + e));
  for (double x : {1e-300, -1e-300, 0.1, 0.5, 1.0, 1.5, 2.0, 3.0, 4.0, 5.0, 10.0, 15.0, 20.0, 25.0}) xs.push_back(x);
  FILE* f = std::fopen(out, "w");
  std::fprintf(f, "//@ run-pass\n//@ expect-stdout: ERF_DOUBLE_PRECISION_OK\n");
  std::fprintf(f, "// Generated by stdlib/special/oracles/erf_oracle.cpp: glibc erfl / erfcl in long\n");
  std::fprintf(f, "// double, rounded to double. Prediction before the run: every value within 2 ulp.\n");
  std::fprintf(f, "use special::erf::{erf, erfc}\n\n");
  std::fprintf(f, "fn ulp_of(v: f64) -> f64 with Mut, Div, Panic {\n    var a = v\n    if a < 0.0 { a = 0.0 - a }\n    if a < 2.2250738585072014e-308 { return 4.9406564584124654e-324 }\n");
  std::fprintf(f, "    var u = 2.220446049250313e-16\n    var m = 1.0\n    while a >= 2.0 * m { m = m * 2.0 }\n    while a < m { m = m * 0.5 }\n    u * m\n}\n\n");
  std::fprintf(f, "fn dist(a: f64, b: f64) -> f64 with Mut, Div, Panic {\n    var d = a - b\n    if d < 0.0 { d = 0.0 - d }\n    if b == 0.0 { if a == 0.0 { return 0.0 } return 1.0e300 }\n    d / ulp_of(b)\n}\n\n");
  std::fprintf(f, "fn main() -> i32 with IO, Mut, Div, Panic {\n    let n = %zu\n", xs.size());
  auto arr = [&](const char* name, auto fn) {
    std::fprintf(f, "    let %s: [f64; %zu] = [", name, xs.size());
    for (size_t i = 0; i < xs.size(); ++i) std::fprintf(f, "%s%.16e", i ? ", " : "", fn(xs[i]));
    std::fprintf(f, "]\n");
  };
  arr("xs", [](double x) { return x; });
  arr("ef", [](double x) { return (double)erfl((long double)x); });
  arr("ec", [](double x) { return (double)erfcl((long double)x); });
  std::fprintf(f, "    var worst_f = 0.0\n    var worst_c = 0.0\n    var bad = 0\n    var i = 0\n");
  std::fprintf(f, "    while i < n {\n        let df = dist(erf(xs[i]), ef[i])\n        let dc = dist(erfc(xs[i]), ec[i])\n");
  std::fprintf(f, "        if df > worst_f { worst_f = df }\n        if dc > worst_c { worst_c = dc }\n");
  std::fprintf(f, "        if df > 2.0 || dc > 2.0 { bad = bad + 1; println(xs[i]); println(df); println(dc) }\n        i = i + 1\n    }\n");
  std::fprintf(f, "    print(\"worst ulp erf \"); println(worst_f)\n    print(\"worst ulp erfc \"); println(worst_c)\n");
  std::fprintf(f, "    if bad != 0 { return 1 }\n    println(\"ERF_DOUBLE_PRECISION_OK\")\n    0\n}\n");
  std::fclose(f);
  std::printf("%zu points\n", xs.size());
}
