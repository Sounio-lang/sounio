  for(double x:tx) emit("tan",x,0,0);
  double hx[]={0.5,-3.0,1e-10,10.0,25.0,-25.0,0.0,-0.0,0.01,INF,-INF,NAN_,0.3,1.0,-0.2,21.0};
  for(double x:hx) emit("tanh",x,0,0);
