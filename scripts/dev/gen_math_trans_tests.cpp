  printf("fn is_nan_bits(b: i64) -> bool { let a = b & 0x7FFFFFFFFFFFFFFF\n    a > 0x7FF0000000000000 }\n\n");
  printf("fn chk(id: i64, got: f64, want_bits: i64, tol: i64) -> bool with IO, Mut, Panic, Div {\n    let gb = f64_to_bits(got)\n    var good = false\n    if is_nan_bits(want_bits) { good = is_nan_bits(gb) }\n    else if is_nan_bits(gb) { good = false }\n    else if gb == want_bits { good = true }\n    else if tol == 0 { good = false }\n    else if (gb ^ want_bits) < 0 { good = false }\n    else {\n        var d = gb - want_bits\n        if d < 0 { d = 0 - d }\n        good = d <= tol\n    }\n    if !good {\n        print(\"MISMATCH id=\")\n        print_int(id)\n        print(\" got=\")\n        print_int(gb)\n        print(\" want=\")\n        print_int(want_bits)\n        print(\"\\n\")\n    }\n    good\n}\n\n");
  printf("fn main() -> i64 with IO, Mut, Panic, Div {\n    var ok = true\n");
  double ax[]={0.5,1.0,-2.5,1e-10,123456.789,1e30,-1e300,INF,-INF,0.0,-0.0,NAN_,0.4,1.3,0.9999999999999999,-0.7};
