static int64_t d2b(double d){int64_t b; memcpy(&b,&d,8); return b;}
static double INF=INFINITY, NAN_=NAN;
struct P{std::string n; double x,y; int two;};
static int id=0;
static void emit(const char* fn,double x,double y,int two){
  std::string f=fn; __float128 q;
  if(f=="atan")q=atanq(x); else if(f=="asin")q=asinq(x); else if(f=="acos")q=acosq(x); else if(f=="tan")q=tanq(x);
  else if(f=="tanh")q=tanhq(x); else if(f=="ln")q=logq(x); else q=atan2q(y,x);
  double r=(double)q; bool special = (x==0||std::isinf(x)||std::isnan(x)|| (two&&(y==0||std::isinf(y)||std::isnan(y)))|| std::isnan(r)||std::isinf(r)||r==0 || fabs(r)==1.0);
  int tol=special?0:3;
  if(two) printf("    ok = chk(%d, atan2(bits_to_f64(%lld), bits_to_f64(%lld)), %lld, %d) && ok\n", ++id,(long long)d2b(y),(long long)d2b(x),(long long)d2b(r),tol);
  else printf("    ok = chk(%d, %s(bits_to_f64(%lld)), %lld, %d) && ok\n", ++id,fn,(long long)d2b(x),(long long)d2b(r),tol);
}
