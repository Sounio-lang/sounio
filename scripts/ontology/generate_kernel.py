w("fn ontology_store_fuzzy_local(query: string) -> OntologyTermList {")
w("    var scores: [i64; 16] = [0; 16]")
w("    var indices: [i32; 16] = [0; 16]")
w("    var filled: i64 = 0")
w(f"    var idx: i64 = 0")
w(f"    while idx < {N} {{")
w("        let term = ontology_store_get(idx as i32)")
w("        let sc = tui_score_term(term, query)")
w("        if sc > 0 {")
w("            if filled < 16 {")
w("                scores[filled as usize] = sc")
w("                indices[filled as usize] = idx as i32")
w("                filled = filled + 1")
w("            } else {")
w("                var min_i: i64 = 0")
w("                var j: i64 = 1")
w("                while j < 16 {")
w("                    if scores[j as usize] < scores[min_i as usize] { min_i = j }")
w("                    j = j + 1")
w("                }")
w("                if sc > scores[min_i as usize] {")
w("                    scores[min_i as usize] = sc")
w("                    indices[min_i as usize] = idx as i32")
w("                }")
w("            }")
w("        }")
w("        idx = idx + 1")
w("    }")
w("    var swapped = true")
w("    while swapped {")
w("        swapped = false")
w("        var i: i64 = 0")
w("        while i < filled - 1 {")
w("            if scores[i as usize] < scores[(i+1) as usize] {")
w("                let ts = scores[i as usize]")
w("                let ti = indices[i as usize]")
w("                scores[i as usize] = scores[(i+1) as usize]")
w("                indices[i as usize] = indices[(i+1) as usize]")
w("                scores[(i+1) as usize] = ts")
w("                indices[(i+1) as usize] = ti")
w("                swapped = true")
w("            }")
w("            i = i + 1")
w("        }")
w("    }")
w("    var out = ontology_term_list_new()")
w("    var i: i64 = 0")
w("    while i < filled {")
w("        out = ontology_term_list_push(out, ontology_store_get(indices[i as usize]))")
w("        i = i + 1")
w("    }")
w("    out")
w("}")
