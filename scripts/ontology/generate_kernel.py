# store_get
w(f"fn ontology_store_get(idx: i32) -> OntologyTerm {{")
for i, t in enumerate(terms):
    defn = truncate(t.get('definition', ''), 100)
    w(f"    if idx == {i} {{")
    w(f"        var x = ontology_store_make(\"{esc(t['curie'])}\", \"{esc(t['label'])}\", \"{esc(defn)}\", \"{esc(t.get('iri', ''))}\", \"local\")")
    for p in t.get('parents', []):
        w(f"        x = ontology_term_add_parent(x, \"{esc(p)}\")")
    for s in t.get('synonyms', []):
        w(f"        x = ontology_term_add_synonym(x, \"{esc(s)}\")")
    w("        return x")
    w("    }")
w("    ontology_term_empty()")
w("}")
w("")

# Hash index
w("fn hash_curie(curie: string) -> i64 {")
w("    var h: i64 = 5381")
w("    var i: i64 = 0")
w("    while i < str_len(curie) {")
w("        h = ((h * 33) + curie[i as usize] as i64) & 0x7FFFFFFFFFFFFFFF")
w("        i = i + 1")
w("    }")
w("    h")
w("}")
w("")

w(f"fn ontology_index_build() {{")
w("    if HASH_BUILT != 0 { return }")
w(f"    let cap: i64 = {cap}")
w("    var idx: i64 = 0")
w(f"    while idx < {N} {{")
w("        let term = ontology_store_get(idx as i32)")
w("        let h = hash_curie(term.curie)")
w("        var slot = h % cap")
w("        while slot < cap && HASH_KEYS[slot as usize] != 0 {")
w("            slot = slot + 1")
w("            if slot >= cap { slot = 0 }")
w("        }")
w("        HASH_KEYS[slot as usize] = h")
w("        HASH_VALS[slot as usize] = idx as i32")
w("        idx = idx + 1")
w("    }")
w("    HASH_BUILT = 1")
w("}")
w("")

w("fn ontology_store_resolve_fast(curie: string) -> OntologyTerm {")
w("    ontology_index_build()")
w(f"    let cap: i64 = {cap}")
w("    let h = hash_curie(curie)")
w("    var slot = h % cap")
w("    var guard: i64 = 0")
w("    while guard < cap {")
w("        if HASH_KEYS[slot as usize] == 0 { break }")
w("        if HASH_KEYS[slot as usize] == h {")
w("            let vi = HASH_VALS[slot as usize]")
w("            let term = ontology_store_get(vi)")
w("            if term.curie == curie { return term }")
w("        }")
w("        slot = slot + 1")
w("        if slot >= cap { slot = 0 }")
w("        guard = guard + 1")
w("    }")
w("    ontology_term_empty()")
w("}")
w("")

w("fn ontology_store_resolve_local(curie: string) -> OntologyTerm {")
w("    let fast = ontology_store_resolve_fast(curie)")
w("    if ontology_term_found(fast) { return fast }")
w(f"    var idx: i64 = 0")
w(f"    while idx < {N} {{")
w("        let term = ontology_store_get(idx as i32)")
w("        if term.curie == curie {")
w("            return term")
w("        }")
w("        idx = idx + 1")
w("    }")
w("    ontology_term_empty()")
w("}")
w("")

w("fn ontology_store_search_local(query: string) -> OntologyTermList {")
w("    var out = ontology_term_list_new()")
w(f"    var idx: i64 = 0")
w(f"    while idx < {N} {{")
w("        let term = ontology_store_get(idx as i32)")
w("        if str_contains(term.label, query) || str_contains(term.curie, query) {")
w("            out = ontology_term_list_push(out, term)")
w("        }")
w("        var sidx: i64 = 0")
w("        while sidx < term.synonyms_len {")
w("            if str_contains(term.synonyms[sidx as usize], query) {")
w("                out = ontology_term_list_push(out, term)")
w("            }")
w("            sidx = sidx + 1")
w("        }")
w("        idx = idx + 1")
w("    }")
w("    out")
w("}")
w("")

