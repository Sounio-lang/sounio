w("fn ontology_run_batch(path: string) -> i64 with IO, Mut {")
w("    let fd = syscall6(2, path, 0, 0, 0, 0, 0)")
w("    if fd < 0 {")
w("        println(\"ERROR: cannot open batch file \" + path)")
w("        return 1")
w("    }")
w("    let n = syscall6(0, fd, &BATCH_BUF, 4095, 0, 0, 0)")
w("    syscall6(3, fd, 0, 0, 0, 0, 0)")
w("    if n <= 0 {")
w("        println(\"ERROR: empty batch file\")")
w("        return 1")
w("    }")
w("    var line = \"\"")
w("    var i: i64 = 0")
w("    while i < n {")
w("        let c = BATCH_BUF[i as usize] as i64")
w("        if c < 0 { c = c + 256 }")
w("        if c == 10 {")
w("            if str_len(line) > 0 {")
w("                ontology_run_batch_line(line)")
w("            }")
w("            line = \"\"")
w("        } else if c >= 32 && c <= 126 {")
w("            let chars = \" !\\\"#$%&'()*+,-./0123456789:;<=>?@ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\\\]^_`abcdefghijklmnopqrstuvwxyz{|}~\"")
w("            line = line + str_slice(chars, c - 32, c - 31)")
w("        }")
w("        i = i + 1")
w("    }")
w("    if str_len(line) > 0 {")
w("        ontology_run_batch_line(line)")
w("    }")
w("    0")
w("}")
w("")
w("fn ontology_run_batch_line(line: string) -> i64 with IO, Mut {")
