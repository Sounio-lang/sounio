w("    let rest = if spc < 0 { \"\" } else { str_slice(line, spc + 1, str_len(line)) }")
w("    if cmd == \"resolve\" {")
w("        let term = ontology_store_resolve_local(rest)")
w("        if ontology_term_found(term) {")
w("            println(term.curie + \" | \" + term.label)")
w("        } else {")
w("            println(\"unresolved\")")
w("        }")
w("    } else if cmd == \"count\" {")
w("        let count = ontology_count_terms(rest)")
w("        print_int(count as i32)")
w("        println(\" terms\")")
w("    } else if cmd == \"ancestors\" {")
w("        var current = rest")
w("        var depth = 0")
w("        while depth < 8 && str_len(current) > 0 {")
w("            println(current)")
w("            let term = ontology_store_resolve_local(current)")
w("            if term.parents_len == 0 { break }")
w("            current = term.parents[0]")
w("            depth = depth + 1")
w("        }")
w("    } else {")
