#!/usr/bin/env bash
# gen_stdlib_api_md.sh — Generate markdown stdlib API reference
#
# Walks stdlib/**/*.sio, extracts pub fn signatures with preceding /// doc
# comments, and writes docs/stdlib/STDLIB_API_REFERENCE.md grouped by module.
#
# Usage:
#   bash scripts/gen_stdlib_api_md.sh

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
STDLIB_DIR="${REPO_ROOT}/stdlib"
OUT_FILE="${REPO_ROOT}/docs/stdlib/STDLIB_API_REFERENCE.md"

mkdir -p "$(dirname "${OUT_FILE}")"

# Domain grouping: map top-level directory → display name
declare -A DOMAINS
DOMAINS=(
  [epistemic]="Epistemic Computing"
  [math]="Mathematics"
  [linalg]="Linear Algebra"
  [special]="Special Functions"
  [prob]="Probability"
  [stats]="Statistics"
  [ode]="Differential Equations"
  [integrate]="Numerical Integration"
  [interpolation]="Interpolation"
  [optimize]="Optimization"
  [autodiff]="Automatic Differentiation"
  [cybernetic]="Cybernetics"
  [neuro]="Neuroscience"
  [fmri]="Brain Imaging (fMRI)"
  [connectivity]="Brain Connectivity"
  [medical]="Medical Computing"
  [medlang]="Medical DSL"
  [snn]="Spiking / Hypercomplex Neural Nets"
  [nn]="Neural Networks"
  [ml]="Machine Learning"
  [graph]="Graph Theory"
  [fractal]="Fractal Analysis"
  [plot]="Visualization"
  [causal]="Causal Inference"
  [gpu]="GPU Computing"
  [units]="Units of Measure"
  [data]="Data Structures"
  [collections]="Collections"
  [search]="Search Algorithms"
  [signal]="Signal Processing"
  [quantum]="Quantum Computing"
  [theorem]="Theorem Proving"
  [crypto]="Cryptography"
  [sync]="Concurrency"
  [io]="Input/Output"
  [str]="String Utilities"
  [json]="JSON"
  [toml]="TOML"
  [regex]="Regular Expressions"
  [ontology]="Scientific Ontology"
  [hypercomplex_graph]="Hypercomplex Graphs"
)

total_pub_fn=0
total_modules=0

{
  cat <<'HEADER'
<!-- docs:meta
topic_id: repo.docs.stdlib.stdlib-api-reference
authority: repo_only
audience: users
last_validated: 2026-03-07
validated_by: A3
source_of_truth: docs/governance/topic-registry.v1.json#repo.docs.stdlib.stdlib-api-reference
-->

<!-- AUTO-GENERATED by scripts/gen_stdlib_api_md.sh — do not edit manually -->

# Sounio Standard Library API Reference

This reference lists all public functions (`pub fn`) in the Sounio standard library,
organized by module. Generated from source on the date shown below.

**Generated**: GENDATE
**Source**: `stdlib/**/*.sio`

---

HEADER

  # Collect all top-level directories
  for dir in "${STDLIB_DIR}"/*/; do
    [ -d "$dir" ] || continue
    dirname="$(basename "$dir")"

    # Skip hidden and disabled
    [[ "$dirname" == .* ]] && continue

    # Get display name
    display="${DOMAINS[$dirname]:-$dirname}"

    # Find all .sio files in this module
    mapfile -t sio_files < <(find "$dir" -name '*.sio' -not -name '*.sio.disabled' | sort)
    [ ${#sio_files[@]} -eq 0 ] && continue

    # Collect all pub fn from this module
    module_fns=""
    module_count=0

    for f in "${sio_files[@]}"; do
      rel="${f#${STDLIB_DIR}/}"
      # Extract pub fn lines
      while IFS= read -r line; do
        # Clean leading whitespace
        clean="${line#"${line%%[![:space:]]*}"}"
        module_fns+="- \`${clean}\` — *${rel}*"$'\n'
        ((module_count++)) || true
      done < <(grep -E '^[[:space:]]*(pub[[:space:]]+)?fn[[:space:]]' "$f" | grep 'pub' || true)
    done

    if [ "$module_count" -gt 0 ]; then
      echo "## ${display} (\`stdlib/${dirname}/\`)"
      echo ""
      echo "**${module_count} public functions** across ${#sio_files[@]} files"
      echo ""
      echo "${module_fns}"
      echo "---"
      echo ""
      ((total_pub_fn += module_count)) || true
      ((total_modules++)) || true
    fi
  done

  echo ""
  echo "## Summary"
  echo ""
  echo "- **${total_modules}** modules with public APIs"
  echo "- **${total_pub_fn}** total public functions"
  echo "- Generated from \`stdlib/\` source files"

} > "${OUT_FILE}.tmp"

# Replace date placeholder
sed -i "s/GENDATE/$(date +%Y-%m-%d)/" "${OUT_FILE}.tmp"
mv "${OUT_FILE}.tmp" "${OUT_FILE}"

echo "[gen_stdlib_api_md] Wrote ${total_pub_fn} pub fn across ${total_modules} modules → ${OUT_FILE}"
