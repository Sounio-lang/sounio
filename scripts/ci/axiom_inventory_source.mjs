function generate(output,list) {
  const paths=[...new Set(fs.readFileSync(list,'utf8').split('\0').filter(p=>p&&!p.startsWith('formal/lake/packages/')))].sort(compare);
  const axioms=new Map(),nd=new Map(),sorries=new Map();
  for(const p of paths){const s=scan(fs.readFileSync(p,'utf8'));if(s.axioms.length)axioms.set(p,s.axioms);if(s.nd)nd.set(p,s.nd);if(s.sorry)sorries.set(p,s.sorry);}
  const sum=m=>[...m.values()].reduce((a,b)=>a+b,0);
  const nAx=[...axioms.values()].reduce((a,b)=>a+b.length,0),nNd=sum(nd),nSorry=sum(sorries);
  const L=historicalText.slice(0,12),w=s=>L.push(s);
  w(`| \`.lean\` files scanned | ${paths.length} |`);
  w(`| \`sorry\` in code | ${nSorry} |`);
  w(`| \`axiom\` declarations | ${nAx}, in ${axioms.size} files |`);
  w(`| \`native_decide\` uses | ${nNd}, in ${nd.size} files |`);
  L.push(...historicalText.slice(12,19));
  for(const p of [...axioms.keys()].sort((a,b)=>axioms.get(b).length-axioms.get(a).length||compare(a,b))){
    w(`### \`${p}\` (${axioms.get(p).length})`);w('');w('| Line | Axiom |');w('|---:|---|');
    for(const [line,name]of axioms.get(p))w(`| ${line} | \`${name}\` |`);w('');
  }
  if(sorries.size){w('## `sorry` in code');w('');w('| File | Count |');w('|---|---:|');for(const p of [...sorries.keys()].sort(compare))w(`| \`${p}\` | ${sorries.get(p)} |`);w('');}
  L.push(...historicalText.slice(19,23));
  for(const p of [...nd.keys()].sort((a,b)=>nd.get(b)-nd.get(a)||compare(a,b)))w(`| \`${p}\` | ${nd.get(p)} |`);
  L.push(...historicalText.slice(23));
  fs.writeFileSync(output,L.join('\n')+'\n');
  console.error(`files=${paths.length} axioms=${nAx} axiom_files=${axioms.size} native_decide=${nNd} native_decide_files=${nd.size} sorry=${nSorry}`);
}
if(process.argv[2]==='--selftest')selftest();
else {const [output,list]=process.argv.slice(2);if(!output||!list)throw Error('OUTPUT NUL_FILE_LIST required');generate(output,list);}
