function strip(source) {
  const src = Array.from(source.replace(/\r\n?/g, '\n'));
  const out = [];
  let i = 0, depth = 0, inString = false;
  while (i < src.length) {
    const c = src[i], next = src[i + 1] ?? '';
    if (depth > 0) {
      if (c === '/' && next === '-') { depth++; out.push('  '); i += 2; }
      else if (c === '-' && next === '/') { depth--; out.push('  '); i += 2; }
      else { out.push(c === '\n' ? '\n' : ' '); i++; }
    } else if (inString) {
      if (c === '\\' && i + 1 < src.length) {
        out.push(next === '\n' ? '\n' : ' ', ' '); i += 2;
      } else if (c === '"') { inString = false; out.push('"'); i++; }
      else { out.push(c === '\n' ? '\n' : ' '); i++; }
    } else if (c === '/' && next === '-') { depth = 1; out.push('  '); i += 2; }
    else if (c === '-' && next === '-') {
      while (i < src.length && src[i] !== '\n') { out.push(' '); i++; }
    } else if (c === '"') { inString = true; out.push('"'); i++; }
    else { out.push(c); i++; }
  }
  return out.join('');
}
// Python's previous Unicode whitespace/word semantics, not JS's ASCII \b.
const ws = '[\\u0009-\\u000d\\u001c-\\u0020\\u0085\\u00a0\\u1680\\u2000-\\u200a\\u2028\\u2029\\u202f\\u205f\\u3000]';
const axiom = new RegExp('^' + ws + '*(?:(?:private|protected|noncomputable|unsafe)' + ws + '+)*axiom' + ws + '+([^' + ws.slice(1,-1) + ':({\\[]+)', 'u');
const word = name => new RegExp('(?<![\\p{L}\\p{N}_])' + name + '(?![\\p{L}\\p{N}_])', 'gu');
const compare = (a,b) => {
  const aa=Array.from(a),bb=Array.from(b);
  for(let i=0;i<Math.min(aa.length,bb.length);i++) {
    const d=aa[i].codePointAt(0)-bb[i].codePointAt(0); if(d!==0)return d;
  }
  return aa.length-bb.length;
};
function scan(source) {
  const code=strip(source), axioms=[];
  code.split('\n').forEach((line,i)=>{const m=axiom.exec(line);if(m)axioms.push([i+1,m[1]]);});
  return {axioms,nd:[...code.matchAll(word('native_decide'))].length,sorry:[...code.matchAll(word('sorry'))].length};
}
function selftest() {
  assert.deepEqual(scan('/- axiom hidden : False /- sorry -/ native_decide -/\naxiom real : True'),{axioms:[[2,'real']],nd:0,sorry:0});
  assert.deepEqual(scan('def s := "axiom hidden sorry native_decide \\" still string"\n-- sorry\nprivate protected noncomputable unsafe axiom α : True'),{axioms:[[3,'α']],nd:0,sorry:0});
  assert.deepEqual(scan('sorry sorryé éyet_sorry sorry٢ native_decide native_decideΩ Ωnative_decide'),{axioms:[],nd:1,sorry:1});
  assert.deepEqual(scan('/-- doc -/\r\n\u0085axiom Ω(x : Nat) : True\runsafe axiom β{u} : True'),{axioms:[[2,'Ω'],[3,'β']],nd:0,sorry:0});
  assert.equal(strip('"a\\\nb"\naxiom a : True').split('\n').length,3);
  assert.deepEqual(scan('def sorryElse := 1 -- axiom no : False\n/- unfinished sorry\naxiom no : False'),{axioms:[],nd:0,sorry:0});
  assert(compare('\u{10000}','\ue000')>0);
  console.log('AXIOM_SOURCE_SCANNER_SELFTEST_PASS controls=7 nested_comments=strings=unicode=prefixes=line_numbers=checked');
}

