#!/usr/bin/env bash
# Generate formal/Bootstrap/SeedData.lean from the seed files, as Lean lists of
# byte values. Each list is written in chunks of 256 so that the elaborator does
# not recurse too deeply. Usage: bootstrap/model/gen_seed_data.sh [out]
set -euo pipefail
root="$(cd "$(dirname "$0")/../.." && pwd)"
out="${1:-$root/formal/Bootstrap/SeedData.lean}"

gen() { # name file
  local name="$1" file="$2" i=0
  echo "/-- ${file} -/"
  od -An -v -tu1 "$root/$file" | tr -s ' \n' '\n' | sed '/^$/d' | split -l 256 - "$tmp/c."
  local parts=()
  for c in "$tmp"/c.*; do
    printf 'def %s_%d : List Nat := [%s]\n' "$name" "$i" "$(paste -sd, "$c" | sed 's/,/, /g')"
    parts+=("${name}_${i}")
    i=$((i + 1))
  done
  rm -f "$tmp"/c.*
  local IFS='+'
  printf 'def %s : List Nat :=\n  %s\n\n' "$name" "$(echo "${parts[*]}" | sed 's/+/ ++ /g')"
}

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
{
  cat <<'HEAD'
/-
Generated by bootstrap/model/gen_seed_data.sh from the files named below;
do not edit. The gate regenerates it and fails on any difference.
-/
namespace X86Min.Data

HEAD
  gen seedA bootstrap/roots/a/seed-a
  gen seedAHex bootstrap/roots/a/seed-a.hex
  gen seedAOct bootstrap/roots/a/seed-a.oct
  gen seedB bootstrap/roots/b/seed-b
  gen seedBOct bootstrap/roots/b/seed-b.oct
  gen seedBHex bootstrap/roots/b/seed-b.hex
  echo 'end X86Min.Data'
} > "$out"
