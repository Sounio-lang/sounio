// C++23 independent Boost100-digit erfc oracle for scalar Normal kernels.
// Extended log tails use the DLMF7.12 Mills asymptotic only above |x|1000.
// Existing Normal probability-relative/log-absolute limit2e-10 is retained;
// tiny log complements additionally retain relative accuracy/subnormal values.
