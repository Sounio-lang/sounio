using B=boost::multiprecision::cpp_dec_float_100;
using Words=std::array<std::int64_t,4>;
std::int64_t bits(double x){return std::bit_cast<std::int64_t>(x);}
double from(std::int64_t x){return std::bit_cast<double>(x);}
std::vector<double> cases(){
 std::vector<double> out;
 auto add=[&](double x){if(!std::isfinite(x))throw std::runtime_error("nonfinite fixture input");if(std::none_of(out.begin(),out.end(),[&](double y){return bits(x)==bits(y);}))out.push_back(x);};
 for(int k=-128;k<=128;++k)add((40.0*static_cast<double>(k))/128.0);
 for(double a:{0.0,std::numeric_limits<double>::denorm_min(),std::numeric_limits<double>::min(),1e-200,1e-12,1e-8,.001,.5,1.,5.,8.,10.,20.,37.,38.,38.25,38.5,39.,40.,100.,1000.,1e100,1e154,1.8e154,1e308,std::numeric_limits<double>::max()}){add(a);add(-a);}
 for(double center:{std::sqrt(3.0),0.6744897501960817,38.46740561714434}){
  double low=center,high=center;add(center);add(-center);
  for(int k=0;k<4;++k){low=std::nextafter(low,0.0);high=std::nextafter(high,std::numeric_limits<double>::infinity());add(low);add(-low);add(high);add(-high);}
 }
 return out;
}
std::array<B,4> reference(double x){
 B a=abs(B(x)),small,logsmall;
 if(a<=1000){
  B scaled=a/sqrt(B(2));
  small=boost::math::erfc(scaled)/2;
  logsmall=log(small);
 }else{
  // Alternating Mills expansion; at a>1000 the next term after16 is tiny.
  B inverse=1/(a*a),term=1,sum=1;
  for(unsigned n=1;n<=16;++n){term*= -B(2*n-1)*inverse;sum+=term;}
  logsmall= -a*a/2-log(a)-log(2*boost::math::constants::pi<B>())/2+log(sum);
  // The scalar probability and its large-tail logarithm underflow in f64.
  small=0;
 }
 B large=1-small,negative=-small;
 B loglarge=boost::math::log1p(negative);
 if(std::signbit(x))return {small,large,logsmall,loglarge};
 return {large,small,loglarge,logsmall};
}
std::string word(std::int64_t x){if(x==std::numeric_limits<std::int64_t>::min())return "(0-9223372036854775807-1)";return std::to_string(x);}
void generate(){
 auto v=cases();
 std::cout<<R"SIO(// Generated by the independent C++23 oracle; input words are exact.
use stats::normal_scalar::{normal_cdf_scalar,normal_sf_scalar,normal_logcdf_scalar,normal_logsf_scalar}
fn bit(v:f64)->i64 {f64_to_bits(v)}
fn row(id:i64,x:f64) with IO,Mut,Div,Panic {
 print("ROW ");print(id);print(" ");print(bit(x));print(" ")
 print(bit(normal_cdf_scalar(x)));print(" ")
 print(bit(normal_sf_scalar(x)));print(" ")
 print(bit(normal_logcdf_scalar(x)));print(" ")
 println(bit(normal_logsf_scalar(x)))
}
)SIO";
 for(std::size_t first=0;first<v.size();first+=32){
  std::cout<<"fn chunk"<<first/32<<"() with IO,Mut,Div,Panic {\n";
  for(std::size_t i=first;i<std::min(first+32,v.size());++i)std::cout<<" row("<<i<<",bits_to_f64("<<word(bits(v[i]))<<"))\n";
  std::cout<<"}\n";
 }
 std::cout<<"fn main() with IO,Mut,Div,Panic {\n";
 for(std::size_t first=0;first<v.size();first+=32)std::cout<<" chunk"<<first/32<<"()\n";
 std::cout<<" println(\"NORMAL_SCALAR_ROWS "<<v.size()<<"\")\n}\n";
}
bool read_row(const std::string&line,std::size_t&id,std::int64_t&input,Words&w){
 std::istringstream s(line);std::string tag,extra;
 if(!(s>>tag>>id>>input>>w[0]>>w[1]>>w[2]>>w[3])||tag!="ROW")return false;
 return !(s>>extra);
}
int verify(const char*path,bool strict_application=false){
 std::ifstream in(path);if(!in)throw std::runtime_error("missing output");
 auto v=cases();std::size_t next=0;bool done=false;unsigned errors=0;double maxrel=0,maxlog=0,maxtiny=0,maxnormalrel=0,maxnormaltiny=0,maxsubnormalulp=0,maxapplicationlog=0;
 auto fail=[&](const std::string&m){if(errors<20)std::cerr<<"NORMAL_SCALAR_FAIL row="<<next<<" "<<m<<"\n";++errors;};
 const B denorm(std::numeric_limits<double>::denorm_min()),limit("2e-10"),maximum(std::numeric_limits<double>::max()),normalminimum(std::numeric_limits<double>::min());
 std::string line;
 while(std::getline(in,line)){
  if(line.rfind("NORMAL_SCALAR_ROWS ",0)==0){std::istringstream s(line.substr(19));std::size_t n=0;std::string extra;if(done||!(s>>n)||(s>>extra)||n!=v.size()||next!=v.size())fail("invalid completion");done=true;continue;}
  std::size_t id=0;std::int64_t input=0;Words w{};
  if(done||!read_row(line,id,input,w)||id!=next||next>=v.size()){fail("missing duplicate extra or reordered row");continue;}
  if(input!=bits(v[next]))fail("input identity changed");
  auto ref=reference(v[next]);
  for(unsigned field=0;field<4;++field){
   const double actual=from(w[field]);const B expected=ref[field];
   if(expected>maximum||expected< -maximum){
    if(!std::isinf(actual)||std::signbit(actual)!=(expected<0))fail("unrepresentable log endpoint mismatch");
    continue;
   }
   if(!std::isfinite(actual)){fail("unexpected nonfinite value");continue;}
   if(field<2&&(actual<0||actual>1)){fail("probability outside support");continue;}
   if(field>=2&&actual>0){fail("positive log probability");continue;}
   B error=abs(B(actual)-expected),scale=abs(expected),allowed;
   if(field<2&&scale>=normalminimum)maxnormalrel=std::max(maxnormalrel,(error/scale).convert_to<double>());
   if(field>=2&&scale<B(".125")&&scale>=normalminimum)maxnormaltiny=std::max(maxnormaltiny,(error/scale).convert_to<double>());
   if(scale>0&&scale<normalminimum)maxsubnormalulp=std::max(maxsubnormalulp,(error/denorm).convert_to<double>());
   if(field>=2&&std::abs(v[next])<=40)maxapplicationlog=std::max(maxapplicationlog,error.convert_to<double>());
   if(field<2){
    allowed=limit*scale+4*denorm;
    if(scale>16*denorm&&actual==0)fail("representable tail erased");
    if(scale>denorm)maxrel=std::max(maxrel,(error/scale).convert_to<double>());
   }else{
    allowed=limit;
    if(scale<B(".125")){
     allowed=limit*scale+4*denorm;
     if(scale>denorm)maxtiny=std::max(maxtiny,(error/scale).convert_to<double>());
    }
    if(scale>B("1e6")){
     const double rounded=expected.convert_to<double>();
     const double neighbor=std::nextafter(rounded,0.0);
     allowed=8*abs(B(rounded)-B(neighbor));
    }else maxlog=std::max(maxlog,error.convert_to<double>());
   }
   if(strict_application&&std::abs(v[next])<=40){B application_allowed=B("2e-12")*scale+8*denorm;if(application_allowed<allowed)allowed=application_allowed;}
   if(error>allowed){std::ostringstream m;m<<std::setprecision(18)<<"field="<<field<<" x="<<v[next]<<" actual="<<actual<<" expected="<<expected<<" error="<<error<<" limit="<<allowed;fail(m.str());}
  }
  ++next;
 }
 if(!done||next!=v.size())fail("incomplete nonempty manifest");
 std::cout<<std::setprecision(17)<<"NORMAL_SCALAR_REFERENCE rows="<<v.size()<<" errors="<<errors<<" max_probability_relative="<<maxrel<<" max_log_absolute="<<maxlog<<" max_tiny_log_relative="<<maxtiny<<" max_normal_probability_relative="<<maxnormalrel<<" max_normal_tiny_log_relative="<<maxnormaltiny<<" max_subnormal_ulp="<<maxsubnormalulp<<" max_application_log_absolute="<<maxapplicationlog<<" precision_digits10="<<std::numeric_limits<B>::digits10<<"\n";
 return errors?1:0;
}
void wrong_complement(const char*path){
 std::ifstream in(path);if(!in)throw std::runtime_error("missing mutant input");std::string line;
 while(std::getline(in,line)){
  std::size_t id=0;std::int64_t input=0;Words w{};
  if(read_row(line,id,input,w)){
   w[1]=bits(1.0-from(w[0]));w[2]=bits(std::log(from(w[0])));
   std::cout<<"ROW "<<id<<" "<<input<<" "<<w[0]<<" "<<w[1]<<" "<<w[2]<<" "<<w[3]<<"\n";
  }else std::cout<<line<<"\n";
 }
}
