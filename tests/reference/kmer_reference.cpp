// Independent exact streaming k-mer oracle; C++23, no rolling implementation.
// Each snapshot enumerates every length-k window of the complete prefix.
// Usage: kmer_reference --fixture > genomics_kmer_reference.sio
#include <array>
#include <algorithm>
#include <iostream>
#include <string>
#include <vector>
using V=std::vector<int>;
struct R { std::array<long long,256> bins{};long long windows=0,accepted=0,ambiguous=0,index=0,run=0,n_bins=1;};
R reference(const V& all,int k) {
 R r;for(int j=0;j<k;++j)r.n_bins*=4;
 for(int v:all)if(v>=0&&v<4)++r.accepted;else ++r.ambiguous;
 for(size_t start=0;start+k<=all.size();++start) {
  bool valid=true;int index=0;
  for(int j=0;j<k;++j){int v=all[start+j];if(v<0||v>3){valid=false;break;}index=index*4+v;}
  if(valid){++r.bins[index];++r.windows;}
 }
 // Suffix metadata from scratch, using only final bounded suffix.
 size_t begin=all.size();while(begin>0&&all[begin-1]>=0&&all[begin-1]<4&&all.size()-begin<(size_t)k)--begin;
 r.run=all.size()-begin;
 for(size_t j=begin;j<all.size();++j)r.index=r.index*4+all[j];
 return r;
}
void expected(const R&r) {
 std::cout<<" var bins:[i64;256]=[0;256]\n";
 // Runs also certify every currently unused bin stays exactly zero.
 size_t i=0;
 while(i<256){size_t end=i+1;while(end<256&&r.bins[end]==r.bins[i])++end;
 if(r.bins[i]) {
  if(end-i>=4)std::cout<<" var b"<<i<<"="<<i<<"\n while b"<<i<<"<"<<end<<" { bins[b"<<i<<" as usize]="<<r.bins[i]<<" b"<<i<<"=b"<<i<<"+1 }\n";
  else for(size_t j=i;j<end;++j)std::cout<<" bins["<<j<<"]="<<r.bins[j]<<"\n";
 }
 i=end;
 }
 std::cout<<" verify(s,&bins,"<<r.n_bins<<","<<r.windows<<","<<r.index<<","<<r.run<<","<<r.accepted<<","<<r.ambiguous<<")\n";
}
void emit_snapshot(std::string name,const V& all,int k) {
 std::cout<<"fn "<<name<<"(s:&KmerState) with Mut,Div,Panic {\n";expected(reference(all,k));std::cout<<"}\n";
}
int main(int argc,char**argv) {
 bool fixture=argc>1&&std::string(argv[1])=="--fixture";
 V shortseq={0,1,2,3,-1,0,1,9,2,3,0};
 V stream;
 // Exhaustive 4-mer words separated by ambiguous bases: every bin observed.
 for(int word=0;word<256;++word){stream.push_back((word/64)%4);stream.push_back((word/16)%4);stream.push_back((word/4)%4);stream.push_back(word%4);stream.push_back(-1);}
 if(fixture)std::cout<<"//@ run-pass\n//@ expect-stdout: GENOMICS_KMER_REFERENCE_PASS\n// Generated by independent naive-window C++23 oracle.\nuse genomics::kmer::{KmerState,kmer_new,kmer_push_chunk}\nfn verify(s:&KmerState,bins:&[i64;256],nb:i64,w:i64,ix:i64,run:i64,a:i64,amb:i64) with Mut,Div,Panic {\n assert(s.status==0)\n assert(s.n_bins==nb)\n assert(s.total_windows==w)\n assert(s.rolling_index==ix)\n assert(s.valid_run==run)\n assert(s.accepted_bases==a)\n assert(s.ambiguous_bases==amb)\n var i=0\n while i<256 { assert(s.counts[i as usize]==bins[i as usize]) i=i+1 }\n}\n";
 long long checked=0;
 for(int k=1;k<=4;++k) {
  for(size_t p=0;p<=shortseq.size();++p) {
   V prefix(shortseq.begin(),shortseq.begin()+p);
   if(fixture)emit_snapshot("prefix_"+std::to_string(k)+"_"+std::to_string(p),prefix,k);
   else {auto r=reference(prefix,k);std::cout<<"short\t"<<k<<"\t"<<p<<"\t"<<r.windows<<"\t"<<r.accepted<<"\t"<<r.ambiguous<<"\n";}
   ++checked;
  }
  for(int p:{0,256,512,768,1024,1280}) {
   V prefix(stream.begin(),stream.begin()+p);auto r=reference(prefix,k);
   if(p==1280) {
    for(int b=0;b<r.n_bins;++b)if(r.bins[b]!=(5-k)*(256/r.n_bins))return 2;
    if(r.windows!=256*(5-k)||r.accepted!=1024||r.ambiguous!=256||r.index!=0||r.run!=0)return 3;
   }
   if(fixture)emit_snapshot("stream_"+std::to_string(k)+"_"+std::to_string(p),prefix,k);
   else std::cout<<"stream\t"<<k<<"\t"<<p<<"\t"<<r.windows<<"\t"<<r.accepted<<"\t"<<r.ambiguous<<"\n";
   ++checked;
  }
 }
 if(!fixture){std::cout<<"REFERENCE_SNAPSHOTS\t"<<checked<<"\n";return 0;}
 // Each split test checks both prefix state and final state after boundary.
 for(int k=1;k<=4;++k)for(size_t p=0;p<=shortseq.size();++p) {
  std::cout<<"fn split_"<<k<<"_"<<p<<"() with Mut,Div,Panic {\n var s=kmer_new("<<k<<")\n assert(s.k=="<<k<<")\n var chunk:[i32;256]=[0;256]\n";
  for(size_t j=0;j<p;++j)std::cout<<" chunk["<<j<<"]="<<shortseq[j]<<"\n";
  std::cout<<" assert(kmer_push_chunk(&!s,&chunk,"<<p<<"))\n prefix_"<<k<<"_"<<p<<"(&s)\n";
  for(size_t j=p;j<shortseq.size();++j)std::cout<<" chunk["<<j-p<<"]="<<shortseq[j]<<"\n";
  std::cout<<" assert(kmer_push_chunk(&!s,&chunk,"<<shortseq.size()-p<<"))\n prefix_"<<k<<"_"<<shortseq.size()<<"(&s)\n}\n";
 }
 for(int k=1;k<=4;++k) {
  std::cout<<"fn stream_case_"<<k<<"() with Mut,Div,Panic {\n var s=kmer_new("<<k<<")\n var chunk:[i32;256]=[0;256]\n assert(kmer_push_chunk(&!s,&chunk,0))\n stream_"<<k<<"_0(&s)\n";
  for(int off=0;off<1280;off+=256) {
   // Stream literals are generated via base-4 word extraction, distinct from
   // production rolling index and from naive oracle window enumeration.
   std::cout<<" var i"<<off<<"=0\n while i"<<off<<"<256 {\n let pos=(i"<<off<<"+ "<<off<<") as i64\n let word=pos/5\n let place=pos%5\n var v:i32=-1\n if place==0 {v=((word/64)%4) as i32}\n if place==1 {v=((word/16)%4) as i32}\n if place==2 {v=((word/4)%4) as i32}\n if place==3 {v=(word%4) as i32}\n chunk[i"<<off<<" as usize]=v\n i"<<off<<"=i"<<off<<"+1\n }\n assert(kmer_push_chunk(&!s,&chunk,256))\n stream_"<<k<<"_"<<off+256<<"(&s)\n";
  }
  std::cout<<"}\n";
 }
 std::cout<<"fn main() with IO,Mut,Div,Panic {\n";
 for(int k=1;k<=4;++k) {for(size_t p=0;p<=shortseq.size();++p)std::cout<<" split_"<<k<<"_"<<p<<"()\n";std::cout<<" stream_case_"<<k<<"()\n";}
 std::cout<<" println(\"GENOMICS_KMER_REFERENCE_PASS\")\n}\n";
}
